"""SafeDep Post-Install Repair Module.

Implements the Post-Install Repair mode:
1. Assumes the new library version is already installed in the Python environment.
2. Executes the client project's existing test suite (using pytest).
3. If tests fail, identifies the remaining behavioral and runtime issues from test failures.
4. Uses the shared `propose_patch` function from `safedep.patcher` to generate candidate fixes.
5. Applies patches and re-runs the tests.
6. Strictly test-gated: only accepts a patch if tests pass (or the specific failure is resolved).
   If a patch fails tests, the file is immediately reverted.
7. Allows a maximum of 2 retries per issue.
8. Produces a clear report detailing:
   - What was fixed
   - What still failed
   - Explicit note that this mode primarily handles remaining behavioral/runtime issues
"""

from __future__ import annotations

import difflib
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Optional, Union

from .patcher import propose_patch


@dataclass
class PostInstallIssue:
    """Represents a failing issue detected via the test suite during Post-Install Repair."""

    test_name: str
    file_path: str
    line_number: int
    call_expression: str
    error_type: str
    error_message: str
    code_context: str = ""
    attempt_count: int = 0
    fixed: bool = False
    proposed_fix: Optional[str] = None
    patch_diff: Optional[str] = None
    error_output: str = ""
    suggested_fix: Optional[str] = None


@dataclass
class TestSuiteResult:
    """Result of running a test suite (e.g. pytest)."""

    passed: bool
    returncode: int
    stdout: str
    stderr: str
    failed_test_names: list[str] = field(default_factory=list)
    total_tests: int = 0
    failed_count: int = 0


@dataclass
class PostInstallRepairReport:
    """Report generated by Post-Install Repair mode."""

    initial_tests_passed: bool
    final_tests_passed: bool
    total_issues_detected: int
    fixed_count: int
    failed_count: int
    fixed_issues: list[PostInstallIssue] = field(default_factory=list)
    failed_issues: list[PostInstallIssue] = field(default_factory=list)
    patched_files: dict[str, str] = field(default_factory=dict)
    unified_diffs: dict[str, str] = field(default_factory=dict)
    test_output_before: str = ""
    test_output_after: str = ""

    def to_dict(self) -> dict[str, Any]:
        """Convert report to dictionary format."""
        return {
            "mode": "post_install_repair",
            "initial_tests_passed": self.initial_tests_passed,
            "final_tests_passed": self.final_tests_passed,
            "total_issues_detected": self.total_issues_detected,
            "fixed_count": self.fixed_count,
            "failed_count": self.failed_count,
            "fixed_issues": [
                {
                    "test_name": i.test_name,
                    "file_path": i.file_path,
                    "line_number": i.line_number,
                    "call_expression": i.call_expression,
                    "error_type": i.error_type,
                    "error_message": i.error_message,
                    "proposed_fix": i.proposed_fix,
                    "patch_diff": i.patch_diff,
                    "attempts": i.attempt_count,
                }
                for i in self.fixed_issues
            ],
            "failed_issues": [
                {
                    "test_name": i.test_name,
                    "file_path": i.file_path,
                    "line_number": i.line_number,
                    "call_expression": i.call_expression,
                    "error_type": i.error_type,
                    "error_message": i.error_message,
                    "attempts": i.attempt_count,
                    "last_error": i.error_output,
                }
                for i in self.failed_issues
            ],
            "patched_files": list(self.patched_files.keys()),
        }


def run_pytest(
    test_target: Union[str, Path],
    extra_args: Optional[list[str]] = None,
    cwd: Optional[Union[str, Path]] = None,
    env: Optional[dict[str, str]] = None,
) -> TestSuiteResult:
    """Run the test suite using pytest (falling back to unittest if pytest is not available).

    Args:
        test_target: Path to test directory or test file.
        extra_args: Extra arguments to pass to pytest.
        cwd: Working directory for test execution.
        env: Environment variables for test subprocess.

    Returns:
        TestSuiteResult with execution status, returncode, and captured output.
    """
    target_str = str(test_target)
    target_p = Path(target_str)

    # Determine safe working dir and rootdir to avoid directory traversal
    work_dir = Path(cwd) if cwd else (target_p.parent if target_p.is_file() else target_p)

    cmd = [
        sys.executable,
        "-m",
        "pytest",
        f"--rootdir={work_dir}",
        "-p",
        "no:cacheprovider",
        target_str,
        "-v",
        "--tb=short",
    ]
    if extra_args:
        cmd.extend(extra_args)

    exec_env = os.environ.copy()
    if env:
        exec_env.update(env)

    # Avoid writing/loading stale bytecode between rapid source rewrites
    exec_env["PYTHONDONTWRITEBYTECODE"] = "1"

    # Make sure target parent and work_dir are in PYTHONPATH
    search_dirs = [str(work_dir.resolve())]
    if target_p.is_file():
        search_dirs.append(str(target_p.parent.resolve()))

    cur_pythonpath = exec_env.get("PYTHONPATH", "")
    for sdir in search_dirs:
        if sdir not in cur_pythonpath:
            cur_pythonpath = f"{sdir}{os.pathsep}{cur_pythonpath}" if cur_pythonpath else sdir
    exec_env["PYTHONPATH"] = cur_pythonpath

    try:
        proc = subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            cwd=str(work_dir),
            env=exec_env,
            check=False,
        )
        stdout = proc.stdout
        stderr = proc.stderr
        returncode = proc.returncode
    except Exception as exc:
        # If pytest fails to execute directly, fallback to unittest discover
        try:
            unit_cmd = [sys.executable, "-m", "unittest", "discover", "-s", str(work_dir)]
            proc = subprocess.run(
                unit_cmd,
                capture_output=True,
                text=True,
                cwd=str(work_dir),
                env=exec_env,
                check=False,
            )
            stdout = proc.stdout
            stderr = proc.stderr
            returncode = proc.returncode
        except Exception as inner_exc:
            return TestSuiteResult(
                passed=False,
                returncode=-1,
                stdout="",
                stderr=f"Failed to run test suite: {exc} | {inner_exc}",
                failed_test_names=[],
                total_tests=0,
                failed_count=1,
            )

    combined_output = stdout + "\n" + stderr
    failed_names: list[str] = []

    # Parse short summary info: e.g. FAILED test_file.py::test_fn - ...
    for match in re.finditer(r"^FAILED\s+([^\s]+)", combined_output, re.MULTILINE):
        failed_names.append(match.group(1))

    # Also match unittest failure lines: FAIL: test_xxx (...) or ERROR: test_xxx (...)
    for match in re.finditer(r"^(?:FAIL|ERROR):\s+([^\s]+)", combined_output, re.MULTILINE):
        failed_names.append(match.group(1))

    # Deduplicate preserving order
    unique_failed: list[str] = []
    for fn in failed_names:
        if fn not in unique_failed:
            unique_failed.append(fn)

    passed = (returncode == 0)

    return TestSuiteResult(
        passed=passed,
        returncode=returncode,
        stdout=stdout,
        stderr=stderr,
        failed_test_names=unique_failed,
        total_tests=max(len(unique_failed), 1) if not passed else 1,
        failed_count=len(unique_failed),
    )


def identify_test_failures(
    test_output: str,
    client_path: Optional[Union[str, Path]] = None,
) -> list[PostInstallIssue]:
    """Parse pytest failure output to extract failing call sites and error details.

    Args:
        test_output: Captured stdout/stderr from pytest.
        client_path: Optional path to client source file or directory to prioritize
                     locating issues inside client code rather than test harnesses.

    Returns:
        List of identified PostInstallIssue instances.
    """
    issues: list[PostInstallIssue] = []
    client_str = str(client_path) if client_path else ""
    client_p = Path(client_str) if client_str else None

    # Determine client filenames / stems if client_path is provided
    client_files: set[str] = set()
    if client_p:
        if client_p.is_file():
            client_files.add(client_p.name)
            client_files.add(str(client_p.resolve()))
        elif client_p.is_dir():
            for f in client_p.glob("**/*.py"):
                client_files.add(f.name)
                client_files.add(str(f.resolve()))

    # Split output into failure blocks by '___+ test_name ___+'
    header_pattern = re.compile(r"_{3,}\s*(.*?)\s*_{3,}")
    sections = header_pattern.split(test_output)

    # First section is prelude; subsequent pairs are (test_name, block_text)
    if len(sections) >= 3:
        for idx in range(1, len(sections), 2):
            test_name = sections[idx].strip()
            block = sections[idx + 1] if idx + 1 < len(sections) else ""
            issue = _parse_single_failure_block(test_name, block, client_files, client_str)
            if issue:
                issues.append(issue)

    # If no blocks were found using the header regex, check for short summary FAILED lines
    if not issues:
        for match in re.finditer(
            r"^FAILED\s+([^\s]+)(?:\s+-\s+(?:([A-Za-z0-9_]+Error|[A-Za-z0-9_]+Exception):\s*(.*)|(.*)))?",
            test_output,
            re.MULTILINE,
        ):
            test_id = match.group(1)
            err_type = match.group(2) or "AssertionError"
            err_msg = match.group(3) or match.group(4) or ""

            # Attempt to extract file and line from test_id: e.g. tests/test_app.py::test_foo
            file_part = test_id.split("::")[0] if "::" in test_id else test_id
            line_no = 1
            call_expr = ""

            # Locate in test_output any line like file_part:12:
            f_match = re.search(re.escape(file_part) + r":(\d+):", test_output)
            if f_match:
                line_no = int(f_match.group(1))

            target_file = file_part
            if client_str and client_p and client_p.is_file():
                target_file = client_str

            issues.append(
                PostInstallIssue(
                    test_name=test_id,
                    file_path=target_file,
                    line_number=line_no,
                    call_expression=call_expr or f"# Failing test: {test_id}",
                    error_type=err_type,
                    error_message=err_msg.strip(),
                    code_context="",
                )
            )

    return issues


def _parse_single_failure_block(
    test_name: str,
    block_text: str,
    client_files: set[str],
    client_str: str,
) -> Optional[PostInstallIssue]:
    """Helper to extract file, line, call expr, and error from one pytest failure block."""
    lines = block_text.splitlines()

    # 1. Extract error type and message: first line starting with 'E   <ErrorType>:' or 'E   '
    err_type = "AssertionError"
    err_msg = ""
    for line in lines:
        e_match = re.match(r"^E\s+([A-Za-z0-9_]+Error|[A-Za-z0-9_]+Exception):\s*(.*)$", line)
        if e_match:
            err_type = e_match.group(1)
            err_msg = e_match.group(2).strip()
            break

    if not err_msg:
        for line in lines:
            if line.startswith("E ") and not line.startswith("E +"):
                err_msg = line[2:].strip()
                break

    # 2. Extract call expression: line starting with '>   '
    call_expr = ""
    for idx, line in enumerate(lines):
        if line.startswith(">") and not line.startswith(">>>"):
            call_expr = line[1:].strip()
            break
        # Fallback for pytest 8/9 short traceback: code line right after file frame
        if ": in " in line and idx + 1 < len(lines):
            next_l = lines[idx + 1]
            if next_l.startswith("    ") and not next_l.strip().startswith("E "):
                call_expr = next_l.strip()

    # 3. Extract file and line frames:
    # Patterns:
    #   path.py:line: in func
    #   File "path.py", line X, in func
    frame_matches = re.findall(
        r'(?:([A-Za-z0-9_./\\-]+\.py):(\d+):|File\s+"([^"]+)",\s+line\s+(\d+))',
        block_text,
    )

    chosen_file = ""
    chosen_line = 1

    # Prefer frames matching client files
    for m in reversed(frame_matches):
        fp = m[0] or m[2]
        ln = int(m[1] or m[3])
        p = Path(fp)
        if p.name in client_files or str(p.resolve()) in client_files:
            chosen_file = fp
            chosen_line = ln
            break

    # If no client frame found, take the frame closest to the error
    if not chosen_file and frame_matches:
        last = frame_matches[-1]
        chosen_file = last[0] or last[2]
        chosen_line = int(last[1] or last[3])

    # Fallback to client_str if provided and file not found
    if not chosen_file and client_str:
        chosen_file = client_str

    if not chosen_file:
        chosen_file = test_name.split("::")[0] if "::" in test_name else "test_target.py"

    return PostInstallIssue(
        test_name=test_name,
        file_path=chosen_file,
        line_number=chosen_line,
        call_expression=call_expr,
        error_type=err_type,
        error_message=err_msg,
        code_context="",
    )


def _resolve_and_map_issue(
    issue: PostInstallIssue,
    client_path: Optional[Union[str, Path]],
    search_dirs: list[Path],
) -> PostInstallIssue:
    """Resolve relative file paths and map test assertions to client source definitions."""
    import ast

    target_p = Path(issue.file_path)
    if not target_p.is_file():
        for sdir in search_dirs:
            cand = sdir / target_p
            if cand.is_file():
                target_p = cand.resolve()
                issue.file_path = str(target_p)
                break

    # Read lines if file is found
    if target_p.is_file():
        try:
            file_lines = target_p.read_text(encoding="utf-8").splitlines()
            if 1 <= issue.line_number <= len(file_lines):
                if not issue.call_expression:
                    issue.call_expression = file_lines[issue.line_number - 1].strip()
                start = max(0, issue.line_number - 4)
                end = min(len(file_lines), issue.line_number + 3)
                issue.code_context = "\n".join(file_lines[start:end])
        except Exception:
            pass

    # If failure is inside a test file and client_path is provided,
    # inspect called client symbols to locate the definition inside client code
    if client_path:
        cp = Path(client_path)
        client_candidates: list[Path] = []
        if cp.is_file():
            client_candidates.append(cp.resolve())
        elif cp.is_dir():
            client_candidates.extend(cp.resolve().glob("**/*.py"))
        else:
            for sdir in search_dirs:
                cand = sdir / cp
                if cand.is_file():
                    client_candidates.append(cand.resolve())
                elif cand.is_dir():
                    client_candidates.extend(cand.resolve().glob("**/*.py"))

        is_test_file = "test" in target_p.name.lower() or "tests" in target_p.parts
        if is_test_file and issue.call_expression:
            try:
                tree = ast.parse(issue.call_expression)
                called_names: list[str] = []
                for n in ast.walk(tree):
                    if isinstance(n, ast.Call):
                        name = getattr(n.func, "id", getattr(n.func, "attr", None))
                        if name:
                            called_names.append(name)

                for cfile in client_candidates:
                    if not cfile.is_file():
                        continue
                    c_text = cfile.read_text(encoding="utf-8")
                    c_tree = ast.parse(c_text)
                    for node in ast.walk(c_tree):
                        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name in called_names:
                            target_lineno = node.lineno
                            # Locate the return statement or first statement
                            for stmt in ast.walk(node):
                                if isinstance(stmt, ast.Return) and hasattr(stmt, "lineno"):
                                    target_lineno = stmt.lineno
                                    break
                            else:
                                if node.body and hasattr(node.body[0], "lineno"):
                                    target_lineno = node.body[0].lineno

                            c_lines = c_text.splitlines()
                            if 1 <= target_lineno <= len(c_lines):
                                issue.file_path = str(cfile)
                                issue.line_number = target_lineno
                                issue.call_expression = c_lines[target_lineno - 1].strip()
                                start = max(0, target_lineno - 4)
                                end = min(len(c_lines), target_lineno + 3)
                                issue.code_context = "\n".join(c_lines[start:end])
                                return issue
            except Exception:
                pass

    return issue



def _invalidate_bytecode_cache(file_path: Union[str, Path]) -> None:
    """Remove stale .pyc / __pycache__ entries for *file_path*."""
    p = Path(file_path).resolve()
    if not p.suffix == ".py":
        return
    adjacent = p.with_suffix(".pyc")
    if adjacent.exists():
        try:
            adjacent.unlink()
        except OSError:
            pass
    cache_dir = p.parent / "__pycache__"
    if cache_dir.is_dir():
        stem = p.stem
        for entry in cache_dir.iterdir():
            if entry.name.startswith(stem + ".") and entry.suffix == ".pyc":
                try:
                    entry.unlink()
                except OSError:
                    pass


def apply_line_patch(
    file_path: Union[str, Path],
    line_number: int,
    old_code: str,
    new_code: str,
) -> tuple[bool, str, str]:
    """Replace old_code with new_code at or around line_number in file_path.

    Returns:
        (success: bool, original_content: str, new_content: str)
    """
    p = Path(file_path)
    if not p.is_file():
        return False, "", ""

    original = p.read_text(encoding="utf-8")
    lines = original.splitlines(keepends=True)

    if not (1 <= line_number <= len(lines)):
        # Try finding line containing old_code
        found_idx = -1
        clean_old = old_code.strip()
        for idx, line in enumerate(lines):
            if clean_old and clean_old in line:
                found_idx = idx
                break
        if found_idx == -1:
            return False, original, original
        target_idx = found_idx
    else:
        target_idx = line_number - 1

    target_line = lines[target_idx]
    clean_old = old_code.strip()
    clean_new = new_code.strip()

    if clean_old in target_line:
        lines[target_idx] = target_line.replace(clean_old, clean_new)
    else:
        # Preserve indentation
        indent = len(target_line) - len(target_line.lstrip())
        leading_space = target_line[:indent]
        ending = "\n" if target_line.endswith("\n") else ""
        lines[target_idx] = f"{leading_space}{clean_new}{ending}"

    modified = "".join(lines)
    p.write_text(modified, encoding="utf-8")
    _invalidate_bytecode_cache(p)
    return True, original, modified


def run_post_install_repair(
    test_target: Union[str, Path],
    client_path: Optional[Union[str, Path]] = None,
    max_retries: int = 2,
    api_key: Optional[str] = None,
    deepseek_model: str = "deepseek-chat",
    cwd: Optional[Union[str, Path]] = None,
    extra_pytest_args: Optional[list[str]] = None,
) -> PostInstallRepairReport:
    """Orchestrate the complete Post-Install Repair workflow.

    1. Assumes the new library is already installed in the environment.
    2. Runs the existing test suite (pytest).
    3. If tests fail, identifies remaining behavioral/runtime issues.
    4. Uses `propose_patch` from `patcher.py` to generate candidate fixes.
    5. Applies each candidate fix and re-runs the test suite.
    6. Strictly test-gated: only keeps the patch if tests pass; reverts on failure.
    7. Retries up to `max_retries` (default 2) per issue.
    8. Returns a comprehensive PostInstallRepairReport.

    Args:
        test_target: Path to test directory or test file.
        client_path: Optional path to client codebase to pinpoint failing files.
        max_retries: Maximum patch attempts per issue (default 2).
        api_key: Optional DeepSeek API key.
        deepseek_model: DeepSeek model identifier.
        cwd: Working directory for running pytest.
        extra_pytest_args: Additional command line arguments for pytest.

    Returns:
        PostInstallRepairReport instance.
    """
    # Step 1: Initial test suite run
    initial_res = run_pytest(test_target, extra_args=extra_pytest_args, cwd=cwd)

    if initial_res.passed:
        # All tests already pass — nothing to repair
        return PostInstallRepairReport(
            initial_tests_passed=True,
            final_tests_passed=True,
            total_issues_detected=0,
            fixed_count=0,
            failed_count=0,
            test_output_before=initial_res.stdout,
            test_output_after=initial_res.stdout,
        )

    # Step 2: Identify test failures from test output
    combined_output = initial_res.stdout + "\n" + initial_res.stderr
    raw_issues = identify_test_failures(combined_output, client_path=client_path)

    target_p = Path(test_target)
    work_dir = Path(cwd) if cwd else (target_p.parent if target_p.is_file() else target_p)
    search_dirs = [work_dir.resolve(), Path.cwd().resolve()]
    if target_p.is_file():
        search_dirs.append(target_p.parent.resolve())
    if client_path:
        cp = Path(client_path)
        search_dirs.append(cp.parent.resolve() if cp.is_file() else cp.resolve())

    issues: list[PostInstallIssue] = []
    for raw_iss in raw_issues:
        issues.append(_resolve_and_map_issue(raw_iss, client_path=client_path, search_dirs=search_dirs))

    fixed_issues: list[PostInstallIssue] = []
    failed_issues: list[PostInstallIssue] = []
    patched_files: dict[str, str] = {}
    unified_diffs: dict[str, str] = {}

    # Step 3: Iterate through detected issues and attempt test-gated repair
    for issue in issues:
        target_path = Path(issue.file_path)
        if not target_path.is_file():
            # If target file cannot be found, mark unresolved
            issue.error_output = f"File not found: {issue.file_path}"
            failed_issues.append(issue)
            continue

        original_content = target_path.read_text(encoding="utf-8")
        current_content = original_content
        issue_resolved = False

        for attempt in range(1, max_retries + 1):
            issue.attempt_count = attempt

            # Build feedback for retry attempts
            feedback = ""
            if attempt > 1:
                feedback = (
                    f"Previous patch attempt failed tests with error: {issue.error_output[:200]}. "
                    f"Adjust the fix to ensure tests pass."
                )

            # Generate fix via shared propose_patch
            breaking_info: dict[str, Any] = {
                "breaking_change": f"Behavioral failure: {issue.error_type}: {issue.error_message}",
                "error_type": issue.error_type,
                "error_message": issue.error_message,
                "code_context": issue.code_context,
                "test_name": issue.test_name,
                "attempt": attempt,
                "feedback": feedback,
            }
            if issue.suggested_fix:
                breaking_info["suggested_fix"] = issue.suggested_fix

            proposed_code = propose_patch(
                code_snippet=issue.call_expression,
                breaking_change_info=breaking_info,
                api_key=api_key,
                model=deepseek_model,
            )

            if not proposed_code or proposed_code == issue.call_expression:
                # Could not generate a different patch
                continue

            # Apply candidate patch to file
            ok, before_patch, after_patch = apply_line_patch(
                file_path=issue.file_path,
                line_number=issue.line_number,
                old_code=issue.call_expression,
                new_code=proposed_code,
            )
            if not ok:
                continue

            # Step 5: Test-gating — Re-run test suite to verify fix
            verify_res = run_pytest(test_target, extra_args=extra_pytest_args, cwd=cwd)

            # Check if this test is still failing
            still_failing = any(
                issue.test_name == fn
                or fn.endswith("::" + issue.test_name)
                or issue.test_name.endswith("::" + fn)
                for fn in verify_res.failed_test_names
            )
            is_test_fixed = (not still_failing) and (verify_res.passed or verify_res.failed_count < initial_res.failed_count)

            if is_test_fixed:
                # ACCEPTED! Keep the patch
                issue.fixed = True
                issue.proposed_fix = proposed_code
                issue.patch_diff = f"- {issue.call_expression}\n+ {proposed_code}"
                current_content = after_patch
                patched_files[issue.file_path] = current_content

                # Create backup file
                backup_path = target_path.with_suffix(target_path.suffix + ".bak")
                if not backup_path.exists():
                    backup_path.write_text(original_content, encoding="utf-8")

                diff = difflib.unified_diff(
                    original_content.splitlines(),
                    current_content.splitlines(),
                    fromfile=f"a/{target_path.name}",
                    tofile=f"b/{target_path.name}",
                    lineterm="",
                )
                unified_diffs[issue.file_path] = "\n".join(diff)

                fixed_issues.append(issue)
                issue_resolved = True
                break
            else:
                # REVERT! Test failed, reject candidate patch
                target_path.write_text(current_content, encoding="utf-8")
                _invalidate_bytecode_cache(target_path)
                issue.error_output = (verify_res.stdout + "\n" + verify_res.stderr)[:300]

        if not issue_resolved:
            failed_issues.append(issue)

    # Step 4: Final test run to verify the overall status
    final_res = run_pytest(test_target, extra_args=extra_pytest_args, cwd=cwd)

    return PostInstallRepairReport(
        initial_tests_passed=initial_res.passed,
        final_tests_passed=final_res.passed,
        total_issues_detected=len(issues),
        fixed_count=len(fixed_issues),
        failed_count=len(failed_issues),
        fixed_issues=fixed_issues,
        failed_issues=failed_issues,
        patched_files=patched_files,
        unified_diffs=unified_diffs,
        test_output_before=initial_res.stdout,
        test_output_after=final_res.stdout,
    )


def format_post_install_report(report: PostInstallRepairReport) -> str:
    """Produce the formatted terminal Post-Install Repair report."""
    border = "=" * 70
    sub_border = "-" * 70

    initial_status = "PASSED" if report.initial_tests_passed else f"FAILED ({report.total_issues_detected} issue(s))"
    final_status = "PASSED (All test suite assertions satisfied)" if report.final_tests_passed else "FAILED (Some issues unresolved)"

    lines = [
        border,
        "  SAFEDEP - POST-INSTALL REPAIR REPORT (TEST-GATED)",
        border,
        "STATUS SUMMARY:",
        f"  * Initial Test Status:                                {initial_status}",
        f"  * Final Test Status:                                  {final_status}",
        f"  * Behavioral Issues Resolved:                         {report.fixed_count}",
        f"  * Unresolved Issues:                                  {report.failed_count}",
        sub_border,
        "IMPORTANT NOTE ON POST-INSTALL REPAIR:",
        "  [!] Post-Install Repair assumes the new library version is ALREADY installed.",
        "  [!] It specializes in resolving BEHAVIORAL and runtime incompatibilities",
        "      (e.g., changed return value formats, altered algorithm semantics, new exceptions)",
        "      that can ONLY be detected by running the client project's test suite (pytest).",
        "  [!] All patches are TEST-GATED: candidate fixes are only kept if pytest confirms",
        "      the tests pass. If a proposed fix fails tests, it is immediately reverted.",
        "  [!] Maximum 2 retries per issue are attempted.",
        sub_border,
    ]

    # Section 1: Resolved Issues
    if report.fixed_issues:
        lines.append(f"\n[+] RESOLVED BEHAVIORAL ISSUES ({report.fixed_count}):")
        lines.append("    (Verified passing by client project test suite)\n")
        for idx, iss in enumerate(report.fixed_issues, 1):
            fname = Path(iss.file_path).name
            lines.append(f"  {idx}. [FIXED] Test `{iss.test_name}` in {fname}:{iss.line_number}")
            lines.append(f"     Error:        {iss.error_type}: {iss.error_message}")
            lines.append(f"     Old Code:     {iss.call_expression}")
            lines.append(f"     Accepted Fix: {iss.proposed_fix}")
            lines.append(f"     Retries Used: {iss.attempt_count} / 2")
            if iss.patch_diff:
                lines.append(f"     Diff:         {iss.patch_diff.replace(chr(10), ' | ')}")
            lines.append("     Verification: PASSED (Test-gated assertion satisfied)")
            lines.append("")

    # Section 2: Unresolved Issues
    if report.failed_issues:
        lines.append(f"\n[x] UNRESOLVED ISSUES ({report.failed_count}):")
        lines.append("    (Retries exhausted; proposed patches failed test gating)\n")
        for idx, iss in enumerate(report.failed_issues, 1):
            fname = Path(iss.file_path).name
            lines.append(f"  {idx}. [UNRESOLVED] Test `{iss.test_name}` in {fname}:{iss.line_number}")
            lines.append(f"     Error:   {iss.error_type}: {iss.error_message}")
            lines.append(f"     Code:    {iss.call_expression}")
            lines.append(f"     Retries: {iss.attempt_count} / 2 exhausted")
            lines.append("     Status:  REVERTED -> Manual review / investigation required.")
            lines.append("")

    # Section 3: Unified Diffs
    if report.unified_diffs:
        lines.append(sub_border)
        lines.append("ACCEPTED UNIFIED DIFFS:")
        for fp, diff in report.unified_diffs.items():
            lines.append(f"\n--- {fp} ---")
            lines.append(diff.strip())

    lines.append(border)
    return "\n".join(lines)
